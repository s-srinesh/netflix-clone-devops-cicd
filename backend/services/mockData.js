/**
 * Helper to slice or rotate catalog array for various category tabs
 */
function getCategoryList(list, category) {
  const categories = {
    now_playing: [0, 4],
    top_rated: [1, 5],
    popular: [2, 6],
    upcoming: [3, 7],
    airing_today: [0, 3],
    on_the_air: [1, 4],
  };

  const range = categories[category] || [0, list.length];
  const start = range[0] % list.length;
  return [...list.slice(start), ...list.slice(0, start)];
}

/**
 * Returns trailer object array for given ID
 */
function getTrailersForId(id, type) {
  const list = type === 'tv' ? MOCK_TV : MOCK_MOVIES;
  const item = list.find((m) => m.id === Number(id)) || list[0];
  const key = item.trailerKey || (type === 'tv' ? 'b9EkMc79ZSU' : 'EXeTwQWrcwY');

  return [
    {
      id: `trailer-${id}-1`,
      iso_639_1: 'en',
      iso_3166_1: 'US',
      name: `${item.title || item.name} Official Trailer`,
      key,
      site: 'YouTube',
      size: 1080,
      type: 'Trailer',
      official: true,
      published_at: '2023-01-01T00:00:00.000Z',
    },
  ];
}

/**
 * Intercepts TMDB URLs and returns matching mock structure
 */
export function getFallbackForUrl(url) {
  const parsed = new URL(url);
  const pathname = parsed.pathname;

  // 1. Trending Movie
  if (pathname.includes('/trending/movie')) {
    return { page: 1, results: MOCK_MOVIES };
  }

  // 2. Trending TV Show
  if (pathname.includes('/trending/tv')) {
    return { page: 1, results: MOCK_TV };
  }

  // 3. Movie Trailers: /3/movie/:id/videos
  const movieVideoMatch = pathname.match(/\/movie\/(\d+)\/videos/);
  if (movieVideoMatch) {
    const id = movieVideoMatch[1];
    return { id: Number(id), results: getTrailersForId(id, 'movie') };
  }

  // 4. TV Trailers: /3/tv/:id/videos
  const tvVideoMatch = pathname.match(/\/tv\/(\d+)\/videos/);
  if (tvVideoMatch) {
    const id = tvVideoMatch[1];
    return { id: Number(id), results: getTrailersForId(id, 'tv') };
  }

  // 5. Similar Movies: /3/movie/:id/similar
  const movieSimilarMatch = pathname.match(/\/movie\/(\d+)\/similar/);
  if (movieSimilarMatch) {
    const id = Number(movieSimilarMatch[1]);
    return { page: 1, results: MOCK_MOVIES.filter((m) => m.id !== id) };
  }

  // 6. Similar TV: /3/tv/:id/similar
  const tvSimilarMatch = pathname.match(/\/tv\/(\d+)\/similar/);
  if (tvSimilarMatch) {
    const id = Number(tvSimilarMatch[1]);
    return { page: 1, results: MOCK_TV.filter((t) => t.id !== id) };
  }

  // 7. Movie Details: /3/movie/:id
  const movieDetailMatch = pathname.match(/\/movie\/(\d+)$/);
  if (movieDetailMatch) {
    const id = Number(movieDetailMatch[1]);
    const movie = MOCK_MOVIES.find((m) => m.id === id) || MOCK_MOVIES[0];
    return movie;
  }

  // 8. TV Details: /3/tv/:id
  const tvDetailMatch = pathname.match(/\/tv\/(\d+)$/);
  if (tvDetailMatch) {
    const id = Number(tvDetailMatch[1]);
    const tv = MOCK_TV.find((t) => t.id === id) || MOCK_TV[0];
    return tv;
  }

  // 9. Movie Categories: /3/movie/:category
  const movieCatMatch = pathname.match(/\/movie\/([a-z_]+)/);
  if (movieCatMatch) {
    const cat = movieCatMatch[1];
    return { page: 1, results: getCategoryList(MOCK_MOVIES, cat) };
  }

  // 10. TV Categories: /3/tv/:category
  const tvCatMatch = pathname.match(/\/tv\/([a-z_]+)/);
  if (tvCatMatch) {
    const cat = tvCatMatch[1];
    return { page: 1, results: getCategoryList(MOCK_TV, cat) };
  }

  // 11. Search Movie
  if (pathname.includes('/search/movie')) {
    const query = parsed.searchParams.get('query') || '';
    const qLower = query.toLowerCase();
    const results = MOCK_MOVIES.filter((m) => m.title.toLowerCase().includes(qLower));
    return { page: 1, results: results.length ? results : MOCK_MOVIES.slice(0, 3) };
  }

  // 12. Search TV
  if (pathname.includes('/search/tv')) {
    const query = parsed.searchParams.get('query') || '';
    const qLower = query.toLowerCase();
    const results = MOCK_TV.filter((t) => t.name.toLowerCase().includes(qLower));
    return { page: 1, results: results.length ? results : MOCK_TV.slice(0, 3) };
  }

  // 13. Search Person
  if (pathname.includes('/search/person')) {
    const query = parsed.searchParams.get('query') || '';
    const qLower = query.toLowerCase();
    const results = MOCK_PERSONS.filter((p) => p.name.toLowerCase().includes(qLower));
    return { page: 1, results: results.length ? results : MOCK_PERSONS };
  }

  // Default fallback: return movie collection
  return { page: 1, results: MOCK_MOVIES };
}
